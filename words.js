// İçerik kalite kontrolü. Oyun mantığı hiçbir şekilde buna bağlı değildir —
// yalnızca geliştirme sırasında veri bütünlüğünü kontrol etmek için tarayıcı
// konsolundan elle çağrılır: validateWords()
// ---------------------------------------------------------------------------
function validateWords() {
  const pool = window.WORDS_POOL;
  const normalize = (s) =>
    (s || "")
      .trim()
      .toLocaleLowerCase("tr")
      .replace(/\s+/g, " ");

  const report = {
    total: pool.length,
    missingForbidden: [],
    fewerThan7: [],
    duplicateMainWords: [],
    duplicateForbiddenInCard: [],
    mainWordInForbidden: [],
    emptyStrings: [],
    tooLongMainWord: [],
    unknownCategory: [],
  };

  const seenWords = new Map();

  pool.forEach((card) => {
    const key = normalize(card.word);

    if (!card.word || !key) {
      report.emptyStrings.push(card.id);
    }

    if (key) {
      if (seenWords.has(key)) {
        report.duplicateMainWords.push([seenWords.get(key), card.id, card.word]);
      } else {
        seenWords.set(key, card.id);
      }
    }

    if (card.word && card.word.trim().split(/\s+/).length > 3) {
      report.tooLongMainWord.push({ id: card.id, word: card.word });
    }

    const forbidden = card.forbidden || [];
    if (forbidden.length === 0) {
      report.missingForbidden.push(card.id);
    } else if (forbidden.length < 7) {
      report.fewerThan7.push({ id: card.id, word: card.word, count: forbidden.length });
    }

    forbidden.forEach((f) => {
      if (!f || !f.trim()) report.emptyStrings.push(card.id);
    });

    const forbiddenNorm = forbidden.map(normalize).filter(Boolean);
    if (new Set(forbiddenNorm).size !== forbiddenNorm.length) {
      report.duplicateForbiddenInCard.push({ id: card.id, word: card.word });
    }
    if (key && forbiddenNorm.includes(key)) {
      report.mainWordInForbidden.push({ id: card.id, word: card.word });
    }

    if (!window.WORD_CATEGORIES.some((c) => card.id >= c.from && card.id <= c.to)) {
      report.unknownCategory.push(card.id);
    }
  });

  console.log("%c[Tabu Validator] Kelime havuzu kalite kontrol raporu", "font-weight:bold;font-size:13px;color:#8F6A31;");
  console.table({
    "Toplam kart": report.total,
    "Eksik yasaklı listesi": report.missingForbidden.length,
    "7'den az yasaklısı olan": report.fewerThan7.length,
    "Duplicate ana kelime": report.duplicateMainWords.length,
    "Kart içi duplicate yasaklı": report.duplicateForbiddenInCard.length,
    "Ana kelime = yasaklı kelime": report.mainWordInForbidden.length,
    "Boş string": report.emptyStrings.length,
    "Çok uzun ana kelime (3+ kelime)": report.tooLongMainWord.length,
    "Tanınmayan kategori": report.unknownCategory.length,
  });

  if (report.duplicateMainWords.length) console.warn("Duplicate ana kelimeler:", report.duplicateMainWords);
  if (report.fewerThan7.length) console.warn("7'den az yasaklısı olan kartlar:", report.fewerThan7);
  if (report.duplicateForbiddenInCard.length) console.warn("Kart içi duplicate yasaklı kelimeler:", report.duplicateForbiddenInCard);
  if (report.mainWordInForbidden.length) console.warn("Ana kelime = yasaklı kelime olan kartlar:", report.mainWordInForbidden);
  if (report.unknownCategory.length) console.warn("Kategorisi bulunamayan kartlar:", report.unknownCategory);
  if (report.tooLongMainWord.length) console.warn("Çok uzun ana kelimeler:", report.tooLongMainWord);

  return report;
}
window.validateWords = validateWords;
